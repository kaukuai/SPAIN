export const guideFor = key => GUIDE[key] || null;

// Place achievements as wish items, so they earn XP, stamps and badges and sync with the team.
export function guideQuests() {
  const out = [];
  for (const [place, g] of Object.entries(GUIDE)) {
    const city = place.split('|')[0];
    for (const [id, emoji, title, points = 10] of g.quests || []) {
      out.push({ id, type: 'do', city, cities: [city], emoji, title, note: `${LABEL[g.kind]}成就・${place.split('|')[1]}`, points, tags: TAG[g.kind], place, quest: true });
    }
  }
  return out;
}
